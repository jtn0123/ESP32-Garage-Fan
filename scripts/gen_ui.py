# Resolve repository root similarly to other generators.
# SCons deletes __file__ from the globals it exec()s pre-scripts with, so when it is
# missing walk up from the working directory (PlatformIO leaves it wherever pio was
# launched, e.g. firmware/arduino) until the repo's layout markers appear.
try:
    THIS = pathlib.Path(__file__).resolve()
    ROOT = THIS.parents[1]
except NameError:
    _here = pathlib.Path(os.getcwd()).resolve()
    ROOT = next(
        (
            c
            for c in (_here, *_here.parents)
            if (c / "config").is_dir() and (c / "scripts").is_dir()
        ),
        _here,
    )

UI_SPEC_PATH = ROOT / "config" / "ui_spec.json"
# Repo-relative so generated files are identical regardless of checkout location.
UI_SPEC_REL = "config/ui_spec.json"
FW_OUT_DIR = ROOT / "firmware" / "arduino" / "src"
DEVICE_YAML = ROOT / "config" / "device.yaml"
DEVICE_SAMPLE_YAML = ROOT / "config" / "device.sample.yaml"


def _fail(msg: str) -> None:
    print(f"ERR: {msg}")
    sys.exit(1)


def load_ui_spec() -> Dict[str, Any]:
    if not UI_SPEC_PATH.exists():
        _fail(f"ui spec not found: {UI_SPEC_PATH}")

    def _strip_json_comments(text: str) -> str:
        out: list[str] = []
        i = 0
        n = len(text)
        in_string = False
        escape = False
        in_line_comment = False
        in_block_comment = False
        while i < n:
            ch = text[i]
            nxt = text[i + 1] if i + 1 < n else ""
            if in_line_comment:
                if ch == "\n":
                    in_line_comment = False
                    out.append(ch)
                i += 1
                continue
            if in_block_comment:
                if ch == "*" and nxt == "/":
                    in_block_comment = False
                    i += 2
                else:
                    i += 1
                continue
            if in_string:
                out.append(ch)
                if escape:
                    escape = False
                elif ch == "\\":
                    escape = True
                elif ch == '"':
                    in_string = False
                i += 1
                continue
            # Detect start of string
            if ch == '"':
                in_string = True
                out.append(ch)
                i += 1
                continue
            # Detect // line comment
            if ch == "/" and nxt == "/":
                in_line_comment = True
                i += 2
                continue
            # Detect /* block comment */
            if ch == "/" and nxt == "*":
                in_block_comment = True
                i += 2
                continue
            # Detect # line comment (YAML-style), allowed outside strings
            if ch == "#":
                in_line_comment = True
                i += 1
                continue
            out.append(ch)
            i += 1
        return "".join(out)

    try:
        raw = UI_SPEC_PATH.read_text()
        data = json.loads(_strip_json_comments(raw))
    except Exception as e:
        _fail(f"failed to parse {UI_SPEC_PATH}: {e}")
    # Minimal validation
    if data.get("schema") != "ui-spec@1":
        _fail('ui_spec.json must contain "schema": "ui-spec@1"')
    if not isinstance(data.get("canvas"), dict):
        _fail("ui_spec.json missing canvas object")
    if not isinstance(data.get("rects"), dict) or not data["rects"]:
        _fail("ui_spec.json missing rects map")
    if not isinstance(data.get("components"), dict) or not data["components"]:
        _fail("ui_spec.json missing components map")
    if not isinstance(data.get("variants"), dict) or not data["variants"]:
        _fail("ui_spec.json missing variants map")
    return data


def emit_fw_header(spec: Dict[str, Any]) -> str:
    canvas = spec.get("canvas", {})
    w = int(canvas.get("w", 250))
    h = int(canvas.get("h", 122))
    # Build explicit variant ordering: MINIMAL=0 if present, then V1, V2 if present
    variants = spec.get("variants", {})
    order: list[str] = []
    if "minimal" in variants:
        order.append("minimal")
    for name in ["v1", "v2"]:
        if name in variants:
            order.append(name)
    # Fallback: append any others not already listed in sorted order
    for name in sorted(variants.keys()):
        if name not in order:
            order.append(name)
    lines: list[str] = []
    lines.append("// AUTO-GENERATED by scripts/gen_ui.py — DO NOT EDIT")
    lines.append(f"// source: {UI_SPEC_REL}")
    lines.append("// schema: ui-spec@1")
    lines.append("#pragma once")
    lines.append("")
    lines.append("// Basic UI spec info")
    lines.append("namespace ui {")
    lines.append("struct SpecInfo { int canvas_w; int canvas_h; };")
    lines.append(f"static constexpr SpecInfo SPEC{{ {w}, {h} }};")
    lines.append("enum VariantId {")
    for idx, name in enumerate(order):
        lines.append(f"    UIVAR_{name.upper()} = {idx},")
    lines.append("};")
    lines.append("}")
    lines.append("")
    # Emit icon tokens so tests can find weather-* references in the header
    try:
        icon_names = [
            r.get("icon")
            for r in (spec.get("iconMap") or [])
            if isinstance(r, dict) and r.get("icon")
        ]
        weather_icons = sorted(
            {n for n in icon_names if isinstance(n, str) and n.startswith("weather-")}
        )
        if weather_icons:
            lines.append("// Icon tokens: " + " ".join(weather_icons))
    except Exception:
        pass
    return "\n".join(lines) + "\n"


