def emit_fw_layout_header(spec: Dict[str, Any]) -> str:
    import hashlib

    canvas = spec.get("canvas", {})
    rects = spec.get("rects", {})
    w = int(canvas.get("w", 250))
    h = int(canvas.get("h", 122))
    digest = hashlib.md5(
        json.dumps({"canvas": canvas, "rects": rects}, sort_keys=True).encode("utf-8")
    ).hexdigest()
    # Compute CRC32 over canonical canvas+rects for parity check
    crc = (
        zlib.crc32(json.dumps({"canvas": canvas, "rects": rects}, sort_keys=True).encode("utf-8"))
        & 0xFFFFFFFF
    )
    layout_version = int(spec.get("layoutVersion", spec.get("version", 1)))

    def emitted_name(name: str) -> str:
        # Prefix RECT_ for parity with tests, and avoid STATUS collision
        base = "STATUS_" if name == "STATUS" else name
        return f"RECT_{base}"

    lines: list[str] = []
    lines.append("// AUTO-GENERATED by scripts/gen_ui.py — DO NOT EDIT")
    lines.append(f"// source: {UI_SPEC_REL}")
    lines.append("// schema: ui-spec@1")
    lines.append("#pragma once")
    lines.append("")
    lines.append("// Layout identity for simulator ↔ firmware parity checks")
    lines.append(f"#define LAYOUT_VERSION {layout_version}")
    lines.append(f"#define LAYOUT_CRC 0x{crc:08X}u")
    lines.append(f'#define LAYOUT_MD5 "{digest}"')
    lines.append("")
    lines.append("// Display dimensions")
    lines.append(f"#define DISPLAY_WIDTH {w}")
    lines.append(f"#define DISPLAY_HEIGHT {h}")
    lines.append("")
    lines.append("// Partial update windows (x, y, w, h) — generated from ui_spec.json")
    for name, xywh in rects.items():
        x, y, rw, rh = [int(v) for v in xywh]
        var = emitted_name(name)
        lines.append(f"static constexpr int {var}[4] = {{ {x:3d}, {y:3d}, {rw:3d}, {rh:2d}}};")
    lines.append("")
    lines.append("enum WeatherIconId {")
    lines.append("    ICON_CLEAR = 0,")
    lines.append("    ICON_PARTLY,")
    lines.append("    ICON_CLOUDY,")
    lines.append("    ICON_RAIN,")
    lines.append("    ICON_STORM,")
    lines.append("    ICON_SNOW,")
    lines.append("    ICON_FOG,")
    lines.append("};")
    lines.append("")
    lines.append("// Compile-time layout sanity checks (widths/heights within bounds)")
    for name, xywh in rects.items():
        x, y, rw, rh = [int(v) for v in xywh]
        var = emitted_name(name)
        lines.append(f'static_assert({var}[0] >= 0 && {var}[1] >= 0, "{name} origin");')
        lines.append(f'static_assert({x} + {rw} <= DISPLAY_WIDTH,  "{name} width");')
        lines.append(f'static_assert({y} + {rh} <= DISPLAY_HEIGHT, "{name} height");')
    if "STATUS" in rects:
        lines.append(
            "static_assert(RECT_STATUS_[0] + RECT_STATUS_[2] <= DISPLAY_WIDTH, " '"STATUS_ width");'
        )
    lines.append("")
    return "\n".join(lines) + "\n"


def _config_fw_version() -> str:
    """fw_version from config/device.yaml (or the committed sample), '' if unset.

    Mirrors gen_device_header.py: the first existing file wins; no fall-through
    from device.yaml to the sample when the key is merely absent.
    """
    for path in (DEVICE_YAML, DEVICE_SAMPLE_YAML):
        if not path.exists():
            continue
        try:
            txt = path.read_text()
        except Exception:
            return ""
        if yaml is not None:
            try:
                data = yaml.safe_load(txt) or {}
                return str(data.get("fw_version", "") or "")
            except Exception:
                return ""
        m = re.search(r"^fw_version:\s*[\"']?([^\"'\n#]+)", txt, re.M)
        return m.group(1).strip() if m else ""
    return ""


def resolve_fw_version(allow_git: bool = False) -> str:
    """Resolve the version stamped into ui_generated.js as UI_FW_VERSION.

    Priority mirrors gen_device_header.py so the simulator shows the same
    version as the firmware: generated_config.h (present after a firmware
    build), then config/device.yaml or the committed sample, then $FW_VERSION.
    git-describe is opt-in (--git-version): stamping it by default made every
    regeneration at a new commit churn the committed ui_generated.js.
    """
    gen_cfg = FW_OUT_DIR / "generated_config.h"
    try:
        m = re.search(r'#define\s+FW_VERSION\s+"([^"]+)"', gen_cfg.read_text())
        if m:
            return m.group(1)
    except Exception:
        pass
    version = _config_fw_version() or os.environ.get("FW_VERSION", "")
    if version:
        return version
    if allow_git:
        for cmd in (
            ["git", "describe", "--tags", "--always", "--dirty"],
            ["git", "rev-parse", "--short", "HEAD"],
        ):
            try:
                return (
                    subprocess.check_output(cmd, cwd=ROOT, stderr=subprocess.DEVNULL)
                    .decode("utf-8", "ignore")
                    .strip()
                )
            except Exception:
                continue
    return "dev"


def emit_web_js(spec: Dict[str, Any], fw_version: str) -> str:
    js_obj = json.dumps(spec, separators=(",", ":"))
    # Compute layout identity for the browser too
    canvas = spec.get("canvas", {})
    rects = spec.get("rects", {})
    layout_version = int(spec.get("layoutVersion", spec.get("version", 1)))
    crc = (
        zlib.crc32(json.dumps({"canvas": canvas, "rects": rects}, sort_keys=True).encode("utf-8"))
        & 0xFFFFFFFF
    )
    lines: list[str] = []
    lines.append("// AUTO-GENERATED by scripts/gen_ui.py - DO NOT EDIT")
    lines.append("window.UI_SPEC = " + js_obj + ";")
    lines.append("window.UI_FW_VERSION = " + json.dumps(fw_version) + ";")
    lines.append("window.UI_LAYOUT_VERSION = " + json.dumps(layout_version) + ";")
    lines.append('window.UI_LAYOUT_CRC = "0x%08X";' % crc)
    lines.append(
        (
            "(function(){"
            " function _mapWeather(iconMap, weather){"
            " var s=String(weather||'').toLowerCase();"
            " if(!iconMap||!Array.isArray(iconMap)) return null;"
            " for(var i=0;i<iconMap.length;i++){"
            " var rule=iconMap[i];"
            " if(rule && Array.isArray(rule.match)){"
            " for(var j=0;j<rule.match.length;j++){"
            " var m=rule.match[j];"
            " if(s.indexOf(String(m).toLowerCase())>=0) return rule.icon;"
            " } } else if(rule && rule.default){ return rule.icon; } }"
            " return null; }"
            " window.uiMapWeather = function(w){"
            " var spec = window.UI_SPEC || {};"
            " return _mapWeather(spec.iconMap, w); };"
            " })();"
        )
    )
    return "\n".join(lines) + "\n"


